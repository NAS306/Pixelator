"use strict";

const assert = require("assert");
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");

assert(!html.includes("/*__PIXELATOR_STYLES__*/"), "CSS build marker remains");
assert(!html.includes("/*__PIXELATOR_SCRIPTS__*/"), "JavaScript build marker remains");
assert(html.includes("Generated by build.js"), "generated file banner is missing");

const inlineScript = html.match(/<script>([\s\S]*?)<\/script>/);
assert(inlineScript, "inline application script is missing");
new Function(inlineScript[1]);

global.window = {};
require(path.join(root, "src", "palettes.js"));
require(path.join(root, "src", "color-space.js"));
require(path.join(root, "src", "outline.js"));
require(path.join(root, "src", "webm-muxer.js"));
require(path.join(root, "src", "webcodecs-encoder.js"));
require(path.join(root, "src", "pixelate.js"));
require(path.join(root, "src", "adaptive-palette.js"));
require(path.join(root, "src", "gif-decoder.js"));

const P = global.window.Pixelator;
assert.deepStrictEqual(P.parseCustomPalette("#fff, #000000 invalid #fff"), ["#ffffff", "#000000"]);
assert.strictEqual(P.getPalette("gameboy").length, 4);
assert.strictEqual(P.getPalette("adaptive16"), null);
assert.strictEqual(P.getAdaptivePaletteSize("adaptive16"), 16);
assert(Math.abs(P.rgbToOklab(255, 255, 255)[0] - 1) < 0.0001);

const adaptiveSource = { data: new Uint8ClampedArray([
  240, 30, 30, 255, 240, 30, 30, 255,
  30, 220, 60, 255, 30, 220, 60, 255,
  30, 60, 230, 255, 30, 60, 230, 255,
  245, 220, 40, 255, 245, 220, 40, 255
]) };
const extracted = P.extractAdaptivePalette(adaptiveSource, 4);
assert.strictEqual(extracted.length, 4);
assert(extracted.some((color) => color[0] > 200 && color[1] < 80));

const twoFrameGif = new Uint8Array([
  0x47, 0x49, 0x46, 0x38, 0x39, 0x61,
  0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00,
  0x00, 0x00, 0x00, 0xff, 0xff, 0xff,
  0x21, 0xf9, 0x04, 0x00, 0x0a, 0x00, 0x00, 0x00,
  0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00,
  0x02, 0x02, 0x44, 0x01, 0x00,
  0x21, 0xf9, 0x04, 0x00, 0x14, 0x00, 0x00, 0x00,
  0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00,
  0x02, 0x02, 0x4c, 0x01, 0x00, 0x3b
]);
const decodedGif = P.decodeGif(twoFrameGif.buffer);
assert.strictEqual(decodedGif.duration, 0.3);
assert.strictEqual(decodedGif.frameCount, 2);
assert.strictEqual(decodedGif.hasTransparency, false);
assert.strictEqual(decodedGif.frames[0].indices[0], 0);
assert.strictEqual(decodedGif.frames[1].indices[0], 1);
const transparentGifBytes = twoFrameGif.slice();
for (let index = 0; index < transparentGifBytes.length - 3; index += 1) {
  if (transparentGifBytes[index] === 0x21 && transparentGifBytes[index + 1] === 0xf9) transparentGifBytes[index + 3] = 0x01;
}
assert.strictEqual(P.decodeGif(transparentGifBytes.buffer).hasTransparency, true);

const pixels = {
  data: new Uint8ClampedArray([
    5, 8, 10, 255,
    246, 244, 240, 255,
    100, 110, 120, 0
  ])
};
P.applyPalette(pixels, 3, 1, P.getPalette("mono"), "none");
assert.deepStrictEqual(Array.from(pixels.data.slice(0, 3)), [17, 17, 22]);
assert.deepStrictEqual(Array.from(pixels.data.slice(4, 7)), [244, 240, 232]);
assert.deepStrictEqual(Array.from(pixels.data.slice(8, 12)), [100, 110, 120, 0]);

const transparentPixel = { data: new Uint8ClampedArray([220, 80, 40, 255]) };
assert.strictEqual(P.hasTransparency(transparentPixel), false);
const outlined = P.buildOutlinedPixels(transparentPixel, 1, 1, [10, 20, 30], 1);
assert.deepStrictEqual([outlined.width, outlined.height], [3, 3]);
assert.deepStrictEqual(Array.from(outlined.data.slice(0, 4)), [10, 20, 30, 255]);
assert.deepStrictEqual(Array.from(outlined.data.slice(16, 20)), [220, 80, 40, 255]);
assert.strictEqual(P.hasTransparency({ data: new Uint8ClampedArray([0, 0, 0, 0]) }), true);

const webm = P.muxWebm([
  { type: "key", timestamp: 0, duration: 41667, data: new Uint8Array([0x9d, 0x01, 0x2a]) },
  { type: "delta", timestamp: 41667, duration: 41667, data: new Uint8Array([0x01, 0x02]) }
], { codecId: "V_VP8", width: 96, height: 64, fps: 24, durationSeconds: 0.083334 });
assert.deepStrictEqual(Array.from(webm.slice(0, 4)), [0x1a, 0x45, 0xdf, 0xa3]);
assert(webm.length > 80);
assert.strictEqual(typeof P.WebmFrameEncoder, "function");

console.log("Smoke tests passed");
