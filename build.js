"use strict";

const fs = require("fs");
const path = require("path");

const root = __dirname;
const source = path.join(root, "src");
const output = path.join(root, "index.html");
const backup = path.join(root, "index_BU.html");
const scriptFiles = [
  "state.js",
  "palettes.js",
  "color-space.js",
  "pixelate.js",
  "adaptive-palette.js",
  "gif-metadata.js",
  "media.js",
  "renderer.js",
  "exporter.js",
  "ui.js",
  "app.js"
];

function read(file) {
  return fs.readFileSync(path.join(source, file), "utf8").trim();
}

const template = read("template.html");
const styles = read("styles.css");
const scripts = scriptFiles.map((file) => `// ---- ${file} ----\n${read(file)}`).join("\n\n");

if (!template.includes("/*__PIXELATOR_STYLES__*/") || !template.includes("/*__PIXELATOR_SCRIPTS__*/")) {
  throw new Error("template.html에서 빌드 삽입 지점을 찾을 수 없습니다.");
}

const result = template
  .replace("/*__PIXELATOR_STYLES__*/", styles)
  .replace("/*__PIXELATOR_SCRIPTS__*/", scripts)
  .replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build.js. Edit src/* and rebuild. -->");

if (fs.existsSync(output)) fs.copyFileSync(output, backup);
fs.writeFileSync(output, result + "\n", "utf8");

const sizeKb = (Buffer.byteLength(result, "utf8") / 1024).toFixed(1);
console.log(`Built ${path.basename(output)} (${sizeKb} KB)`);
if (fs.existsSync(backup)) console.log(`Backup ${path.basename(backup)} updated`);
